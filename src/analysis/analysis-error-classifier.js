import { ANALYSIS_ERROR_CODES } from "./analysis-errors.js";

const RETRYABLE_ANALYSIS_ERRORS = new Set([
  ANALYSIS_ERROR_CODES.ANALYSIS_WORKER_FAILED,
  ANALYSIS_ERROR_CODES.ANALYSIS_START_FAILED,
  ANALYSIS_ERROR_CODES.ANALYSIS_SAVE_FAILED,
  ANALYSIS_ERROR_CODES.RATE_LIMITED
]);

export function isRetryableAnalysisError(code) {
  return RETRYABLE_ANALYSIS_ERRORS.has(code);
}
